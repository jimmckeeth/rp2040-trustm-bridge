#!/usr/bin/env python3
"""
Generate trustm/_generated.py from the Infineon host library headers.

The host and the firmware have to agree on OIDs, RNG types and status codes.
Transcribing them by hand is how the two drift apart, so they are parsed
straight out of the library the firmware is actually compiled against.

Anything that is not in a C header - the chip's own error codes, which live
only in the Solution Reference Manual - is hand-maintained in const.py.

    ./tools/gen_const.py            # rewrite trustm/_generated.py
    ./tools/gen_const.py --check    # exit 1 if it is out of date
"""

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "subs", "arduino-optiga-trust-m", "src")
OUT = os.path.join(ROOT, "trustm", "_generated.py")

RETURN_CODES_H = os.path.join(SRC, "optiga_trustm", "optiga_lib_return_codes.h")
LIB_COMMON_H = os.path.join(SRC, "optiga_trustm", "optiga_lib_common.h")
LIB_VERSION_H = os.path.join(SRC, "optiga_trustm", "optiga_lib_version.h")
WRAPPER_H = os.path.join(SRC, "OPTIGATrustM.h")

DEFINE = re.compile(r"^#define\s+(\w+)\s+\((0x[0-9A-Fa-f]+)\)")
DOC = re.compile(r"^\s*///\s*(.*?)\s*$")
ENUMERATOR = re.compile(r"^\s*(e?[A-Z][A-Z_0-9]*)\s*=\s*(0x[0-9A-Fa-f]+)")


def read(path):
    with open(path, encoding="utf-8", errors="replace") as handle:
        return handle.read()


def parse_return_codes(path):
    """[(name, value, description)] in header order, duplicates kept."""
    codes = []
    doc = ""
    for line in read(path).splitlines():
        matched = DOC.match(line)
        if matched:
            doc = matched.group(1)
            continue
        matched = DEFINE.match(line)
        if matched:
            codes.append((matched.group(1), int(matched.group(2), 16), doc))
        doc = ""
    return codes


def parse_enum(path, enum_name, strip_prefix="e"):
    """[(name, value)] for one C enum, with the Infineon 'e' prefix removed."""
    text = read(path)
    start = text.find("enum " + enum_name)
    if start < 0:
        # Infineon writes 'typedef enum eOID_d {' but also 'typedef enum
        # optiga_rng_type'; fall back to searching for the bare name.
        start = text.find(enum_name)
        if start < 0:
            sys.exit(f"enum {enum_name} not found in {path}")
    body_start = text.index("{", start)
    body_end = text.index("}", body_start)

    members = []
    for line in text[body_start:body_end].splitlines():
        matched = ENUMERATOR.match(line)
        if matched:
            name = matched.group(1)
            if strip_prefix and name.startswith(strip_prefix) and name[1:2].isupper():
                name = name[1:]
            members.append((name, int(matched.group(2), 16)))
    if not members:
        sys.exit(f"enum {enum_name} in {path} parsed as empty")
    return members


def parse_lib_version(path):
    matched = re.search(r'#define\s+OPTIGA_LIB_VERSION\s+"([^"]+)"', read(path))
    if not matched:
        sys.exit(f"OPTIGA_LIB_VERSION not found in {path}")
    return matched.group(1).split()[-1]


def render():
    codes = parse_return_codes(RETURN_CODES_H)
    oids = parse_enum(WRAPPER_H, "eOID_d")
    sessions = parse_enum(WRAPPER_H, "eSessionCtxId_d")
    rng = parse_enum(LIB_COMMON_H, "optiga_rng_type", strip_prefix=None)
    key_ids = parse_enum(LIB_COMMON_H, "optiga_key_id", strip_prefix=None)
    key_usages = parse_enum(LIB_COMMON_H, "optiga_key_usage", strip_prefix=None)
    curves = parse_enum(LIB_COMMON_H, "optiga_ecc_curve", strip_prefix=None)
    version = parse_lib_version(LIB_VERSION_H)

    out = [
        '"""',
        "Constants parsed from the Infineon host library headers.",
        "",
        "Generated by tools/gen_const.py - do not edit. Hand-maintained constants",
        "belong in const.py, which re-exports everything here.",
        f"Source: OPTIGA host library {version}.",
        '"""',
        "",
        f'LIB_VERSION = "{version}"',
        "",
        "# Data object identifiers, from eOID_d.",
        "OIDS = {",
    ]
    for name, value in oids:
        out.append(f'    "{name}": 0x{value:04X},')
    out.append("}")
    out.append("")
    out.append("# Session contexts, from eSessionCtxId_d.")
    out.append("SESSION_OIDS = {")
    for name, value in sessions:
        out.append(f'    "{name}": 0x{value:04X},')
    out.append("}")
    out.append("")
    out.append("# Random sources, from optiga_rng_type_t.")
    out.append("RNG_TYPES = {")
    for name, value in rng:
        short = name.replace("OPTIGA_RNG_TYPE_", "").lower()
        out.append(f'    "{short}": 0x{value:02X},')
    out.append("}")
    out.append("")
    out.append("# Key slots, from optiga_key_id_t. SESSION_BASED is 0x0000 - not an")
    out.append("# OID at all, but the value that asks for a volatile session key.")
    out.append("KEY_IDS = {")
    for name, value in key_ids:
        short = name.replace("OPTIGA_KEY_ID_", "").lower()
        out.append(f'    "{short}": 0x{value:04X},')
    out.append("}")
    out.append("")
    out.append("# Key usage flags, from optiga_key_usage_t. These are a bitmask:")
    out.append("# a key may be generated for more than one use at once.")
    out.append("KEY_USAGES = {")
    for name, value in key_usages:
        short = name.replace("OPTIGA_KEY_USAGE_", "").lower()
        out.append(f'    "{short}": 0x{value:02X},')
    out.append("}")
    out.append("")
    out.append("# Elliptic curves, from optiga_ecc_curve_t.")
    out.append("ECC_CURVES = {")
    for name, value in curves:
        short = name.replace("OPTIGA_ECC_CURVE_", "").lower()
        out.append(f'    "{short}": 0x{value:02X},')
    out.append("}")
    out.append("")
    out.append("# Host-library status codes, from optiga_lib_return_codes.h.")
    out.append("# Several modules share 0x0000/0x0001; the first name wins for")
    out.append("# reverse lookup and the rest are listed in RETURN_CODE_ALIASES.")
    out.append("RETURN_CODES = {")
    seen = {}
    aliases = []
    for name, value, doc in codes:
        if value in seen:
            aliases.append((name, value))
            continue
        seen[value] = name
        out.append(f'    0x{value:04X}: ("{name}", "{doc}"),')
    out.append("}")
    out.append("")
    out.append("RETURN_CODE_ALIASES = {")
    for name, value in aliases:
        out.append(f'    "{name}": 0x{value:04X},')
    out.append("}")
    out.append("")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if the generated file is out of date")
    args = parser.parse_args()

    rendered = render()

    if args.check:
        current = read(OUT) if os.path.exists(OUT) else None
        if current != rendered:
            print(f"{OUT} is out of date - run tools/gen_const.py", file=sys.stderr)
            return 1
        print(f"{OUT} is up to date")
        return 0

    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write(rendered)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
